#!/usr/bin/env python3
"""Non-destructive mesh weld repair for a USD asset.

Merges coincident vertices (merge-by-distance) and drops faces degenerated by
the weld, then verifies the candidate. The source asset is never overwritten;
the candidate is written as <stem>.welded<suffix> next to the report.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from mesh_topology_common import (
    analyze_mesh_arrays,
    list_mesh_prims,
    read_mesh_arrays,
    resolve_tolerance,
    sha256_file,
    weld_mesh_arrays,
    write_mesh_arrays,
)
from foundation_common import default_out, write_json

WELDABLE_FINDING_RULES = (
    "CoincidentVerticesChecker",
    "NonManifoldVertexChecker",
    "NonManifoldEdgeChecker",
    "DegenerateFaceChecker",
    "UnreferencedPointsChecker",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("asset", type=Path)
    parser.add_argument("--out", type=Path, required=True, help="Output directory for the candidate and record")
    parser.add_argument("--tolerance", type=float, help="Absolute weld tolerance (default 5e-7 x per-mesh bbox diagonal)")
    parser.add_argument("--mesh-path", help="Only weld the mesh prim at this USD path")
    parser.add_argument("--report", type=Path, help="Optional mesh_topology_report.json to cite as the repair source")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    from pxr import Usd, UsdGeom

    asset = args.asset.resolve()
    out_dir = args.out.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    candidate_path = out_dir / f"{asset.stem}.welded{asset.suffix}"

    def finish(status: str, payload: dict[str, Any], print_path: bool = True) -> int:
        payload.update({
            "schema_version": "1.0",
            "kind": "mesh_repair_weld_record",
            "status": status,
            "source": {"path": str(asset), "sha256": sha256_file(asset) if asset.is_file() else None},
            "candidate": {"path": str(candidate_path), "sha256": sha256_file(candidate_path) if candidate_path.exists() else None},
            "repair_report": str(args.report.resolve()) if args.report else None,
            "rollback": f"Delete {candidate_path}; the source asset is never overwritten.",
            "note": (
                "Relative asset dependencies (textures, MDL) resolve from the source directory. "
                "Validate the candidate alongside a copy of its dependencies, or move the candidate "
                "next to the original textures before reference-sensitive validation."
            ),
        })
        write_json(out_dir / "mesh_repair_weld.json", payload)
        print(out_dir / "mesh_repair_weld.json")
        return 0 if status in ("applied", "no_weld_needed") else 2

    if not asset.is_file():
        return finish("blocked", {"reason": "Input asset does not exist.", "meshes": []})
    stage = Usd.Stage.Open(str(asset))
    if stage is None:
        return finish("blocked", {"reason": "Stage could not be opened.", "meshes": []})

    time = Usd.TimeCode.Default()
    mesh_records: list[dict[str, Any]] = []
    any_welded = False
    for prim in list_mesh_prims(stage):
        prim_path = str(prim.GetPath())
        if args.mesh_path and prim_path != args.mesh_path:
            continue
        geom = UsdGeom.Mesh(prim)
        data = read_mesh_arrays(geom, time)
        if data is None:
            mesh_records.append({"prim_path": prim_path, "status": "skipped", "reason": "animated or malformed mesh arrays"})
            continue
        tolerance = resolve_tolerance(data["points"], args.tolerance)
        before = analyze_mesh_arrays(data["points"], data["face_vertex_counts"], data["face_vertex_indices"], tolerance)
        welded = weld_mesh_arrays(data, tolerance)
        if welded is None:
            mesh_records.append({
                "prim_path": prim_path, "status": "skipped",
                "reason": "unsupported primvar layout for welding", "before": before,
            })
            continue
        new_data, stats = welded
        if stats["points_removed"] == 0 and stats["faces_removed"] == 0:
            mesh_records.append({"prim_path": prim_path, "status": "unchanged", "before": before, "reason": "nothing to weld"})
            continue
        write_mesh_arrays(geom, new_data, time)
        after = analyze_mesh_arrays(new_data["points"], new_data["face_vertex_counts"], new_data["face_vertex_indices"], tolerance)
        mesh_records.append({"prim_path": prim_path, "status": "welded", "before": before, "after": after, "stats": stats})
        any_welded = True

    if not mesh_records:
        return finish("blocked", {"reason": "No mesh prims found.", "meshes": []})
    if not any_welded:
        return finish("no_weld_needed", {"meshes": mesh_records})

    stage.GetRootLayer().Export(str(candidate_path))
    if not candidate_path.is_file():
        return finish("failed", {"reason": "Candidate export failed.", "meshes": mesh_records})

    verify_stage = Usd.Stage.Open(str(candidate_path))
    verified = verify_stage is not None
    if verified:
        for record in mesh_records:
            if record["status"] != "welded":
                continue
            check_prim = verify_stage.GetPrimAtPath(record["prim_path"])
            check_data = read_mesh_arrays(UsdGeom.Mesh(check_prim), time)
            if check_data is None:
                verified = False
                break
            metrics = analyze_mesh_arrays(
                check_data["points"], check_data["face_vertex_counts"], check_data["face_vertex_indices"],
                record["after"]["tolerance"],
            )
            record["verification"] = {
                "coincident_groups_zero": metrics["coincident_groups"] == 0,
                "degenerate_repeated_corner_faces_zero": metrics["degenerate_repeated_corner_faces"] == 0,
                "nonmanifold_vertices_not_worse": metrics["nonmanifold_vertices"] <= record["before"]["nonmanifold_vertices"],
                "verified": (
                    metrics["coincident_groups"] == 0
                    and metrics["degenerate_repeated_corner_faces"] == 0
                    and metrics["nonmanifold_vertices"] <= record["before"]["nonmanifold_vertices"]
                ),
            }
            verified = verified and record["verification"]["verified"]

    status = "applied" if verified else "failed_verification"
    return finish(status, {
        "meshes": mesh_records,
        "verification": {"passed": verified},
        "reason": None if verified else "Candidate did not pass topology re-verification.",
    })


if __name__ == "__main__":
    raise SystemExit(main())
